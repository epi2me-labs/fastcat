"""Generate vendored channel-map C sources from CSV inputs."""

import argparse
import csv
from pathlib import Path


MAP_DIR = Path(__file__).resolve().parent / "data"


def load_map(path):
    rows = []
    x_values = []
    y_values = []
    with open(path, newline="") as handle:
        reader = csv.DictReader(handle, skipinitialspace=True)
        for row in reader:
            channel = int(row["name"])
            xs = []
            ys = []
            for mux in range(1, 5):
                x_key = f"mux_{mux}_phys_x"
                y_key = f"mux_{mux}_phys_y"
                if x_key not in row or y_key not in row:
                    x_key = "mux_1_phys_x"
                    y_key = "mux_1_phys_y"
                x = int(row[x_key])
                y = int(row[y_key])
                xs.append(x)
                ys.append(y)
                x_values.append(x)
                y_values.append(y)
            rows.append((channel, xs, ys))
    return {
        "rows": rows,
        "x_min": min(x_values),
        "x_max": max(x_values),
        "y_min": min(y_values),
        "y_max": max(y_values),
    }


def emit_header():
    return """#ifndef FASTCAT_FC_CHANNEL_MAP_DATA_H
#define FASTCAT_FC_CHANNEL_MAP_DATA_H

#include <stddef.h>
#include <stdint.h>

typedef struct {
    uint16_t channel;
    int16_t x[4];
    int16_t y[4];
} fc_channel_map_channel_row;

extern const fc_channel_map_channel_row fc_channel_map_flongle_rows[];
extern const size_t fc_channel_map_flongle_row_count;
extern const int fc_channel_map_flongle_x_min;
extern const int fc_channel_map_flongle_x_max;
extern const int fc_channel_map_flongle_y_min;
extern const int fc_channel_map_flongle_y_max;

extern const fc_channel_map_channel_row fc_channel_map_minion_rows[];
extern const size_t fc_channel_map_minion_row_count;
extern const int fc_channel_map_minion_x_min;
extern const int fc_channel_map_minion_x_max;
extern const int fc_channel_map_minion_y_min;
extern const int fc_channel_map_minion_y_max;

extern const fc_channel_map_channel_row fc_channel_map_promethion_rows[];
extern const size_t fc_channel_map_promethion_row_count;
extern const int fc_channel_map_promethion_x_min;
extern const int fc_channel_map_promethion_x_max;
extern const int fc_channel_map_promethion_y_min;
extern const int fc_channel_map_promethion_y_max;

#endif
"""


def emit_array(name, data):
    lines = [f"const fc_channel_map_channel_row fc_channel_map_{name}_rows[] = {{"]
    for channel, xs, ys in data["rows"]:
        lines.append(
            "    { %d, { %d, %d, %d, %d }, { %d, %d, %d, %d } },"
            % (channel, xs[0], xs[1], xs[2], xs[3], ys[0], ys[1], ys[2], ys[3]))
    lines.append("};")
    lines.append(f"const size_t fc_channel_map_{name}_row_count = sizeof(fc_channel_map_{name}_rows) / sizeof(fc_channel_map_{name}_rows[0]);")
    lines.append(f"const int fc_channel_map_{name}_x_min = {data['x_min']};")
    lines.append(f"const int fc_channel_map_{name}_x_max = {data['x_max']};")
    lines.append(f"const int fc_channel_map_{name}_y_min = {data['y_min']};")
    lines.append(f"const int fc_channel_map_{name}_y_max = {data['y_max']};")
    lines.append("")
    return "\n".join(lines)


def emit_source(maps):
    parts = [
        '#include "core/fc_channel_map_data.h"',
        "",
        "/* generated by tools/dev-tools generate_channel_map_c from channel map CSV files */",
        "",
    ]
    for name, data in maps:
        parts.append(emit_array(name, data))
    return "\n".join(parts)


def argparser():
    p = argparse.ArgumentParser(
        description="Generate vendored channel-map C sources from bundled CSV inputs.")
    p.add_argument(
        "--out",
        type=Path,
        required=True,
        help="Directory to write fc_channel_map_data.h and fc_channel_map_data.c into")
    return p


def main(args):
    loaded = [
        ("flongle", load_map(MAP_DIR / "asicb512fx_flongle_channel_map.csv")),
        ("minion", load_map(MAP_DIR / "asicb512fx_channel_map.csv")),
        ("promethion", load_map(MAP_DIR / "3000_opx_channel_map.csv")),
    ]
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "fc_channel_map_data.h").write_text(emit_header())
    (args.out / "fc_channel_map_data.c").write_text(emit_source(loaded))


if __name__ == "__main__":
    main(argparser().parse_args())
